def _field(system_prompt: str, label: str) -> str:
    match = re.search(rf"- {label}：(.+)", system_prompt)
    return match.group(1).strip() if match else "【待确认】"


def build_extractive_rag_reply(sources: List[Dict[str, Any]]) -> str:
    """无 LLM 时，用检索片段拼出可追溯的简答。"""
    if not sources:
        return NO_CONTEXT_REPLY

    blocks = ["根据检索到的文档片段："]
    for index, source in enumerate(sources[:3], start=1):
        file_name = source.get("file", "未知文件")
        locator_parts = []
        if source.get("page"):
            locator_parts.append(f"第{source['page']}页")
        if source.get("sheet"):
            locator_parts.append(f"工作表「{source['sheet']}」")
        if source.get("row_start"):
            row_text = f"第{source['row_start']}行"
            if source.get("row_end") and source["row_end"] != source["row_start"]:
                row_text = f"第{source['row_start']}-{source['row_end']}行"
            locator_parts.append(row_text)
        locator = f"（{'；'.join(locator_parts)}）" if locator_parts else ""
        blocks.append(
            f"> 来源：{file_name}{locator}\n>\n"
            f"> {str(source.get('snippet', '')).strip()}\n\n[{index}]"
        )
    blocks.append(
        "\n（当前为本地演示模式，仅复述检索片段；配置 DeepSeek Key 后可生成归纳回答。）"
    )
    return "\n\n".join(blocks)


